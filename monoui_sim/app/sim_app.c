static ui_page_manager_t s_pm;

static ui_widget_t   h_root;
static ui_rect_t     h_bg;
static ui_label_t    h_title;
static ui_label_t    h_sub;
static ui_progress_t h_bar;
static ui_label_t    h_hint;
static ui_page_t     s_page_home;

static void home_animate(void) {
    ui_widget_animate(&h_bar.value,      0.f, 0.82f, 900,  ui_ease_out_elastic, NULL, NULL);
    ui_widget_animate(&h_title.base.alpha, 0.f, 1.f,   350,  ui_ease_out_cubic,   NULL, NULL);
}

static void home_on_appear(ui_page_t *p) { (void)p; home_animate(); }

static void home_on_event(ui_widget_t *self, const ui_event_t *evt) {
    (void)self;
    if (evt->type == UI_EVT_BTN_PRESS && evt->value == 0) {
        /* OK → replay animation */
        home_animate();
    }
}

static const ui_widget_vtbl_t s_home_vtbl = { NULL, home_on_event, NULL };

static void home_build(void) {
    ui_widget_init(&h_root, 0, 0, 256, 64, &s_home_vtbl);

    /* Dark gradient background */
    ui_rect_init(&h_bg, 0, 0, 256, 64, UI_GRAY_BLACK);
    h_bg.gradient   = true;
    h_bg.fill_gray2 = UI_GRAY_SHADOW;
    ui_widget_add_child(&h_root, &h_bg.base);

    /* Title */
    ui_label_init(&h_title, 6, 4, 200, 10,
                  "monoui Demo", &s_font5x8,
                  UI_GRAY_WHITE, UI_GRAY_BLACK, true);
    h_title.align = UI_ALIGN_LEFT;
    ui_widget_add_child(&h_root, &h_title.base);

    /* Subtitle */
    ui_label_init(&h_sub, 6, 15, 200, 9,
                  "SSD1322 256x64 4bpp", &s_font5x8,
                  UI_GRAY_MUTED, UI_GRAY_BLACK, true);
    ui_widget_add_child(&h_root, &h_sub.base);

    /* Animated progress bar */
    ui_progress_init(&h_bar, 6, 30, 204, 10, UI_GRAY_SHADOW, UI_GRAY_LIGHT);
    h_bar.corner_r   = 2;
    h_bar.gradient   = true;
    h_bar.fill_gray2 = UI_GRAY_WHITE;
    ui_widget_add_child(&h_root, &h_bar.base);

    /* Hint */
    ui_label_init(&h_hint, 6, 50, 244, 9,
                  "CW: Settings   Space: replay", &s_font5x8,
                  UI_GRAY_DIM, UI_GRAY_BLACK, true);
    ui_widget_add_child(&h_root, &h_hint.base);

    ui_page_init(&s_page_home, &h_root, home_on_appear, NULL);
}

