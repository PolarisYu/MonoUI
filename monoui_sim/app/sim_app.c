void sim_app_init(void) {
    /* Page manager — ui_core_init() already called by sim_main */
    ui_page_manager_init(&s_pm,
                          ui_core_get_main_canvas(),
                          ui_core_get_trans_canvas());
    ui_core_set_page_manager(&s_pm);

    home_build();
    settings_build();

    ui_page_push(&s_pm, &s_page_home, UI_TRANS_NONE, 0);
}

void sim_app_tick(uint32_t delta_ms) {
    /* Check navigation events first */
    /* (Events were already pushed by sim_main via ui_core_push_event,
       ui_core_tick dispatches them into the widget tree internally.)          */

    /* Custom page navigation logic based on raw input state isn't needed here:
       the page-level navigation is wired through widget on_event callbacks
       or here by checking the pending event before calling tick.

       Simplest approach: wire nav directly in this tick based on page state.  */
    extern const sim_input_state_t *sim_input_state(void);
    static bool prev_cw  = false;
    static bool prev_ccw = false;

    const sim_input_state_t *inp = sim_input_state();

    /* Rising edge: CW → push Settings */
    if (inp->key_enc_cw && !prev_cw) {
        if (!ui_page_is_transitioning(&s_pm) &&
             ui_page_current(&s_pm) == &s_page_home) {
            ui_page_push(&s_pm, &s_page_settings,
                          UI_TRANS_SLIDE_LEFT, UI_TRANS_DURATION_MS);
        }
    }

    /* Rising edge: CCW or Back → pop */
    if ((inp->key_enc_ccw && !prev_ccw) || inp->key_back) {
        if (!ui_page_is_transitioning(&s_pm) &&
             ui_page_current(&s_pm) == &s_page_settings) {
            ui_page_pop(&s_pm, UI_TRANS_SLIDE_RIGHT, UI_TRANS_DURATION_MS);
        }
    }

    prev_cw  = inp->key_enc_cw;
    prev_ccw = inp->key_enc_ccw;

    ui_core_tick(delta_ms);
}
